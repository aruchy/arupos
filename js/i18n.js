let currentLanguage = 'id';

function lookupPath(dict, key) {
  const parts = String(key || '').split('.');
  let node = dict;
  for (const part of parts) {
    if (!node || typeof node !== 'object' || !(part in node)) {
      return undefined;
    }
    node = node[part];
  }
  return node;
}

export function getLanguage() {
  return currentLanguage;
}

export function setLanguage(lang) {
  const safeLang = VALID_LANGUAGES.includes(lang) ? lang : 'id';
  currentLanguage = safeLang;
  if (typeof document !== 'undefined') {
    if (document.documentElement) {
      document.documentElement.lang = safeLang;
    }
    document.title = t('app.title');
  }
  return safeLang;
}

export function getLocale() {
  return currentLanguage === 'en' ? 'en-US' : 'id-ID';
}

export function getMonthsShort() {
  return MONTHS_SHORT[currentLanguage] || MONTHS_SHORT.id;
}

export function getDaysShort() {
  return DAYS_SHORT[currentLanguage] || DAYS_SHORT.id;
}

export function getDaysLong() {
  return DAYS_LONG[currentLanguage] || DAYS_LONG.id;
}

export function resolveReceiptFooter(rawFooter) {
  const clean = String(rawFooter || '').trim();
  if (!clean) {
    return t('receipt.defaultFooter');
  }
  if (currentLanguage === 'en' && DEFAULT_RECEIPT_FOOTERS_ID.has(clean)) {
    return t('receipt.defaultFooter');
  }
  return clean;
}

export function t(key, vars = {}) {
  let value = lookupPath(TRANSLATIONS[currentLanguage], key);
  if (value === undefined) {
    value = lookupPath(TRANSLATIONS.id, key);
  }
  if (value === undefined) {
    return key;
  }
  if (Array.isArray(value)) {
    return [...value];
  }
  if (typeof value !== 'string') {
    return String(value);
  }
  return value.replace(/\{(\w+)\}/g, (match, name) => (
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match
  ));
}

